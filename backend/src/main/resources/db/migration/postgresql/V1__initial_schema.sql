-- Empty PostgreSQL schemas only. No baseline, destructive reset or seed accounts.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN', 'SUPER_ADMIN')),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username)
);
CREATE UNIQUE INDEX uq_single_super_admin ON users (role) WHERE role = 'SUPER_ADMIN';
CREATE INDEX ix_users_created ON users (created_at DESC, id DESC);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    content VARCHAR(4000) NOT NULL,
    type VARCHAR(255) NOT NULL CHECK (type IN ('CHAT', 'FIND_PERSON')),
    status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED', 'HIDDEN', 'DELETED')),
    nickname VARCHAR(255),
    location VARCHAR(255),
    year_range VARCHAR(255),
    author_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP(6) NOT NULL,
    ip_country_code VARCHAR(2),
    ip_country VARCHAR(128),
    ip_region VARCHAR(128),
    ip_city VARCHAR(128),
    ip_location_status VARCHAR(32)
);
CREATE INDEX ix_posts_status_created ON posts (status, created_at DESC, id DESC);
CREATE INDEX ix_posts_type_status_created ON posts (type, status, created_at DESC);
CREATE INDEX ix_posts_author ON posts (author_id);
CREATE INDEX ix_posts_created ON posts (created_at DESC, id DESC);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(2000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED', 'HIDDEN', 'DELETED')),
    created_at TIMESTAMP(6) NOT NULL,
    post_id BIGINT NOT NULL REFERENCES posts(id),
    user_id BIGINT REFERENCES users(id),
    ip_country_code VARCHAR(2),
    ip_country VARCHAR(128),
    ip_region VARCHAR(128),
    ip_city VARCHAR(128),
    ip_location_status VARCHAR(32)
);
CREATE INDEX ix_comments_post_status_created ON comments (post_id, status, created_at, id);
CREATE INDEX ix_comments_user ON comments (user_id);
CREATE INDEX ix_comments_created ON comments (created_at DESC, id DESC);

CREATE TABLE founder_identity (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    created_at TIMESTAMP(6) NOT NULL
);
CREATE TABLE role_change_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    target_user_id BIGINT NOT NULL REFERENCES users(id),
    old_role VARCHAR(255) NOT NULL CHECK (old_role IN ('USER', 'ADMIN', 'SUPER_ADMIN')),
    new_role VARCHAR(255) NOT NULL CHECK (new_role IN ('USER', 'ADMIN', 'SUPER_ADMIN')),
    action VARCHAR(255) NOT NULL CHECK (action IN ('GRANT_ADMIN', 'REVOKE_ADMIN', 'INITIALIZE_FOUNDER')),
    created_at TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_role_audit_target_created ON role_change_audit (target_user_id, created_at DESC);
CREATE INDEX ix_role_audit_actor_created ON role_change_audit (actor_id, created_at DESC);
